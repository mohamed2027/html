/* ----- Language state & helpers ----- */
const LANG = { current: 'ar' };
function t(key, vars) {
  const pair = I18N[key];
  let s = pair ? pair[LANG.current === 'ar' ? 0 : 1] : key;
  if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(String(vars[k])); });
  return s;
}
// Bilingual entity name: prefers current language, falls back to the other one.
function nm(o) {
  if (!o) return '';
  if (typeof o === 'string') return o;
  return LANG.current === 'ar' ? (o.ar || o.en || o.name || '') : (o.en || o.ar || o.name || '');
}
function setLang(l) {
  LANG.current = l === 'en' ? 'en' : 'ar';
  Store.set(APP.langKey, LANG.current);
  document.documentElement.lang = LANG.current;
  document.documentElement.dir = LANG.current === 'ar' ? 'rtl' : 'ltr';
  document.title = t('app.name') + ' · ' + (LANG.current === 'ar' ? 'المخازن' : 'Warehouse');
}
